def nonlinear_pendulum(t, y, beta):
    """Уравнение нелинейного маятника с затуханием"""
    phi, phi_dot = y
    return [phi_dot, -beta * phi_dot - np.sin(phi)]

def simulate_extended(beta, initial_conditions_list, simulation_time=100, dt=0.05):
    """
    Расширенное моделирование с разными начальными условиями
    
    Args:
        beta: параметр затухания
        initial_conditions_list: список начальных условий [(phi0, phi_dot0), ...]
        simulation_time: время моделирования
        dt: шаг по времени
    """
    all_trajectories = []
    
    for phi0, phi_dot0 in initial_conditions_list:
        # Решаем ОДУ
        t_eval = np.arange(0, simulation_time, dt)
        sol = solve_ivp(
            lambda t, y: nonlinear_pendulum(t, y, beta),
            [0, simulation_time],
            [phi0, phi_dot0],
            t_eval=t_eval,
            rtol=1e-8,
            atol=1e-10,
            max_step=0.1
        )
        
        if sol.success:
            all_trajectories.append((sol.t, sol.y[0], sol.y[1]))
    
    return all_trajectories

